// Render the actual calendar component for visual checks, without adding demo data to the app.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const native = require('react-native-web');
const source = fs.readFileSync(path.join(__dirname, '../App.tsx'), 'utf8');
const component = source.slice(source.indexOf('function MonthCalendar('), source.indexOf('export default function App()'));
const styles = source.slice(source.indexOf('const styles=StyleSheet.create('));
const input = `const React=require('react'); const {View,Text,Pressable,StyleSheet}=require('react-native-web');
const weekdays=['日','一','二','三','四','五','六'];const localDate=()=> '2026-10-06';
${component}\n${styles}\nmodule.exports=MonthCalendar;`;
const compiled = ts.transpileModule(input, {compilerOptions:{jsx:ts.JsxEmit.React,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const calendarModule = {exports:{}};
new Function('require','module','exports',compiled)(require,calendarModule,calendarModule.exports);
const Calendar = calendarModule.exports;
const records = [{date:'2026-10-02',total:6.5},{date:'2026-10-05',total:8},{date:'2026-10-06',total:10.5},{date:'2026-10-07',total:0},{date:'2026-10-04',total:9}];
const render = (month,records=[])=>renderToStaticMarkup(React.createElement(Calendar,{month,records,onOpen:()=>{}}));
const markup=render('2026-10',records);
assert.ok(markup.includes('2026-10-07，休息日，0小时，休息'));
assert.ok(markup.includes('2026-10-02，6.5小时，早退'));
for(const mark of ['休','正','早','加']) assert.ok(markup.includes(`>${mark}<`));
assert.ok(markup.includes('2026-10-04，9小时，加班'));
assert.ok(!markup.includes('2026-10-04，休息日'));
assert.ok(markup.includes('2026-10-08，未记录'));
assert.ok(!markup.includes('2026-10-08，休息日'));
assert.equal((render('2024-02').match(/aria-label="2024-02-/g)||[]).length,29);
assert.equal((render('2025-02').match(/aria-label="2025-02-/g)||[]).length,28);
assert.equal((render('2026-03').match(/aria-label="2026-03-/g)||[]).length,31);
const sheet=native.StyleSheet.getSheet();
const html=`<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>工时月历 · 演示数据</title><style>${sheet.textContent}html,body{margin:0;background:#f3f6f2;font-family:system-ui,sans-serif}main{max-width:390px;margin:auto;padding:24px 20px;box-sizing:border-box}h1{font-size:28px;color:#213d32;margin:8px 0 24px}.card{padding:12px;border:1px solid #e6ede5;border-radius:20px;background:#fff}h2{font-size:18px;color:#294a38;margin:4px 4px 20px}.month{text-align:center;font-weight:700;color:#294a38;margin-bottom:20px}.caption{font-size:12px;color:#87978d;margin:18px 0}</style></head><body><main><h1>每日工时</h1><div class="card"><h2>工时月历</h2><div class="month">2026 年 10 月</div>${markup}</div><p class="caption">演示数据 · 7日记录为0小时，自动显示休息</p></main></body></html>`;
fs.writeFileSync(path.join(__dirname,'../dist/calendar-preview.html'),html);
console.log('Calendar render checks passed: four status marks, zero-hour rest, unrecorded days, Sunday overtime, leap February, 31-day month.');
